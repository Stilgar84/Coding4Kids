import type { CodeBlock, WorkspaceState } from '../../types';
import { CurriculumActivity, ExplanationDemoTab, createCurriculumBlock } from './types';

function block(
  type: string,
  repeatCount?: number,
  params?: Record<string, unknown>,
  idPrefix = 'seq'
): CodeBlock {
  return createCurriculumBlock(type, repeatCount, params, idPrefix);
}

function makeMainWorkspace(blocks: CodeBlock[]): WorkspaceState {
  return { MAIN: blocks, F1: [], F2: [], F3: [] };
}

